#!/usr/bin/env node
// Builds the GitHub activity block of the main page from the GitHub GraphQL API.
//
// Writes:
//   images/github-activity.svg   contribution heatmap (one column per week)
//   assets/github-activity.json  total, date range, generation time
//   index.html                   the block between the github-activity markers
//
// Usage: GITHUB_TOKEN=... node scripts/github-activity.mjs
// (locally: GITHUB_TOKEN="$(gh auth token)" node scripts/github-activity.mjs)
//
// No dependencies. Every output is rendered in memory first; when the API call
// or a check fails, the script exits with status 1 and changes no file, so the
// committed files remain the fallback.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const LOGIN = 'luifon';
const PROFILE_URL = `https://github.com/${LOGIN}`;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SVG_PATH = path.join(ROOT, 'images/github-activity.svg');
const JSON_PATH = path.join(ROOT, 'assets/github-activity.json');
const HTML_PATH = path.join(ROOT, 'index.html');
// Subset of JetBrains Mono Regular with only the glyphs of the labels
// (see assets/fonts/README.md). An SVG loaded through <img> cannot load the
// page's fonts, so the subset is embedded in the SVG.
const FONT_PATH = path.join(ROOT, 'assets/fonts/JetBrainsMono-Regular-heatmap.woff2');
const START_MARK = '<!-- github-activity:start (generated by scripts/github-activity.mjs; do not edit by hand) -->';
const END_MARK = '<!-- github-activity:end -->';

// Site palette (assets/site.css).
const BG = '#0a0a0a';
const EMPTY_FILL = '#141414';
const EMPTY_STROKE = '#2a2a2a';
const LABEL = '#858585';
const ACCENT = [0xe6, 0xb4, 0x50];
const LEVEL_SHARES = [0.3, 0.55, 0.8, 1]; // share of the accent over the empty-cell colour

// Geometry in SVG user units.
const CELL = 10;
const STEP = 13; // cell plus gap
const LEFT = 32; // weekday label column
const TOP = 20; // month label row
const FONT_SIZE = 11;

const QUERY = `query($login: String!) {
  user(login: $login) {
    contributionsCollection {
      restrictedContributionsCount
      contributionCalendar {
        totalContributions
        weeks { contributionDays { date weekday contributionCount } }
      }
    }
  }
}`;

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

async function fetchCalendar(token) {
  const res = await fetch('https://api.github.com/graphql', {
    method: 'POST',
    headers: {
      authorization: `bearer ${token}`,
      'content-type': 'application/json',
      'user-agent': 'luifon.github.io github-activity',
    },
    body: JSON.stringify({ query: QUERY, variables: { login: LOGIN } }),
    signal: AbortSignal.timeout(30_000),
  });
  if (!res.ok) throw new Error(`GitHub API returned HTTP ${res.status}`);
  const body = await res.json();
  if (body.errors?.length) throw new Error(`GitHub API error: ${body.errors.map(e => e.message).join('; ')}`);
  const collection = body.data?.user?.contributionsCollection;
  const calendar = collection?.contributionCalendar;
  if (!calendar) throw new Error('GitHub API response has no contribution calendar');
  const weeks = calendar.weeks.map(w => w.contributionDays);
  const days = weeks.flat();
  if (weeks.length < 52 || days.length < 360) throw new Error(`calendar has only ${weeks.length} weeks and ${days.length} days`);
  const sum = days.reduce((n, d) => n + d.contributionCount, 0);
  if (sum !== calendar.totalContributions) throw new Error(`day counts add up to ${sum}, total is ${calendar.totalContributions}`);
  return {
    total: calendar.totalContributions,
    restricted: collection.restrictedContributionsCount,
    weeks,
    from: days[0].date,
    to: days[days.length - 1].date,
  };
}

// Level 0 for no contribution, levels 1-4 by quartile of the days with contributions.
function levelFunction(days) {
  const counts = days.map(d => d.contributionCount).filter(c => c > 0).sort((a, b) => a - b);
  if (!counts.length) return () => 0;
  const q = p => counts[Math.floor(p * (counts.length - 1))];
  const [q1, q2, q3] = [q(0.25), q(0.5), q(0.75)];
  return c => (c <= 0 ? 0 : c <= q1 ? 1 : c <= q2 ? 2 : c <= q3 ? 3 : 4);
}

const hex = rgb => '#' + rgb.map(v => Math.round(v).toString(16).padStart(2, '0')).join('');
const mix = share => {
  const base = [0x14, 0x14, 0x14];
  return hex(base.map((b, i) => b + (ACCENT[i] - b) * share));
};

const formatCount = n => n.toLocaleString('en-US');
const formatDate = iso => {
  const [y, m, d] = iso.split('-').map(Number);
  return `${MONTHS[m - 1]} ${d}, ${y}`;
};
const escapeXml = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function summary(data) {
  return `${formatCount(data.total)} contributions on GitHub from ${formatDate(data.from)} to ${formatDate(data.to)}`;
}

function renderSvg(data, fontBase64) {
  const { weeks } = data;
  const level = levelFunction(weeks.flat());
  const gridWidth = weeks.length * STEP - (STEP - CELL);
  const width = LEFT + gridWidth;
  const legendY = TOP + 7 * STEP + 8;
  const height = legendY + CELL + 2;
  const textY = row => TOP + row * STEP + CELL - 1;
  const charWidth = FONT_SIZE * 0.6; // JetBrains Mono advance width

  const months = [];
  let lastMonth = -1;
  weeks.forEach((days, i) => {
    const month = Number(days[0].date.slice(5, 7)) - 1;
    if (month !== lastMonth) {
      lastMonth = month;
      months.push({ i, month });
    }
  });
  const monthLabels = months.filter((m, k) => {
    const next = months[k + 1];
    if (next && next.i - m.i < 3) return false; // a partial month of one or two weeks
    return m.i * STEP + 3 * charWidth <= gridWidth;
  });

  const fills = [EMPTY_FILL, ...LEVEL_SHARES.map(mix)];
  const cells = fills.map(() => []);
  const cell = (x, y) => `<use href="#c" x="${x}" y="${y}"/>`;
  weeks.forEach((days, i) => {
    for (const d of days) cells[level(d.contributionCount)].push(cell(LEFT + i * STEP, TOP + d.weekday * STEP));
  });

  const moreWidth = 4 * charWidth;
  const legendEnd = width - moreWidth - 6;
  const legendStart = legendEnd - (5 * STEP - (STEP - CELL));
  fills.forEach((_, l) => cells[l].push(cell(legendStart + l * STEP, legendY)));

  const desc = `${summary(data)}. Heatmap with one column per week and one row per weekday; brighter cells mark days with more contributions.`;
  const groups = cells.map((list, l) =>
    l === 0
      ? `<g fill="${fills[0]}" stroke="${EMPTY_STROKE}" stroke-width="1">${list.join('')}</g>`
      : `<g fill="${fills[l]}">${list.join('')}</g>`,
  );

  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-labelledby="t d">`,
    `<title id="t">GitHub contributions of ${LOGIN}</title>`,
    `<desc id="d">${escapeXml(desc)}</desc>`,
    `<style>@font-face{font-family:"JBM";src:url(data:font/woff2;base64,${fontBase64}) format("woff2")}`,
    `text{font-family:"JBM","JetBrains Mono",Menlo,monospace;font-size:${FONT_SIZE}px;fill:${LABEL}}</style>`,
    // The empty-cell stroke lies on the cell edge; inset by half the stroke so all cells have the same outer size.
    `<defs><rect id="c" width="${CELL}" height="${CELL}" rx="2"/><rect id="e" x=".5" y=".5" width="${CELL - 1}" height="${CELL - 1}" rx="1.5"/></defs>`,
    `<rect width="100%" height="100%" fill="${BG}"/>`,
    monthLabels.map(m => `<text x="${LEFT + m.i * STEP}" y="${TOP - 7}">${MONTHS[m.month]}</text>`).join(''),
    `<text x="0" y="${textY(1)}">Mon</text><text x="0" y="${textY(3)}">Wed</text><text x="0" y="${textY(5)}">Fri</text>`,
    groups[0].replace(/href="#c"/g, 'href="#e"'),
    groups.slice(1).join(''),
    `<text x="${legendStart - 6}" y="${legendY + CELL - 1}" text-anchor="end">Less</text>`,
    `<text x="${width}" y="${legendY + CELL - 1}" text-anchor="end">More</text>`,
    '</svg>\n',
  ].join('');
}

function renderBlock(data, svgSize) {
  const version = data.generated_at.slice(0, 10);
  const alt = `Heatmap of GitHub contributions by day: ${summary(data)}.`;
  return [
    START_MARK,
    `      <div class="heatmap"><a href="${PROFILE_URL}"><img src="images/github-activity.svg?v=${version}" width="${svgSize.width}" height="${svgSize.height}" alt="${escapeXml(alt)}" loading="lazy" decoding="async"></a></div>`,
    `      <p class="activity"><span class="strong">${formatCount(data.total)} contributions</span> in the past year · <a href="${PROFILE_URL}" class="more-inline">github.com/${LOGIN}<span aria-hidden="true">↗</span></a></p>`,
    `      ${END_MARK}`,
  ].join('\n');
}

async function main() {
  const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  if (!token) throw new Error('set GITHUB_TOKEN or GH_TOKEN');

  const calendar = await fetchCalendar(token);
  const data = {
    user: LOGIN,
    total: calendar.total,
    restricted_contributions: calendar.restricted,
    from: calendar.from,
    to: calendar.to,
    generated_at: new Date().toISOString(),
  };

  const font = (await readFile(FONT_PATH)).toString('base64');
  const svg = renderSvg({ ...data, weeks: calendar.weeks }, font);
  const [, width, height] = svg.match(/viewBox="0 0 (\d+) (\d+)"/);

  const html = await readFile(HTML_PATH, 'utf8');
  const start = html.indexOf(START_MARK);
  const end = html.indexOf(END_MARK);
  if (start < 0 || end < start) throw new Error('index.html has no github-activity markers');
  const newHtml = html.slice(0, start) + renderBlock(data, { width, height }) + html.slice(end + END_MARK.length);

  await writeFile(SVG_PATH, svg);
  await writeFile(JSON_PATH, JSON.stringify(data, null, 2) + '\n');
  await writeFile(HTML_PATH, newHtml);
  console.log(`github-activity: ${data.total} contributions (${data.restricted_contributions} private) from ${data.from} to ${data.to}; SVG ${svg.length} bytes`);
}

main().catch(err => {
  // The annotation is shown on the workflow run; the committed files stay in place.
  console.error(`::warning title=GitHub activity not updated::${err.message}`);
  process.exit(1);
});
